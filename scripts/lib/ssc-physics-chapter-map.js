function scoreChapter(text, chapterNo) {
  const patterns = CHAPTER_KEYWORDS[chapterNo] ?? [];
  let score = 0;
  const t = String(text ?? "");
  for (const re of patterns) {
    if (re.test(t)) score += 2;
  }
  return score;
}

function mapPhysicsChapter(text) {
  let best = null;
  let bestScore = 0;
  for (const ch of Object.keys(CHAPTER_KEYWORDS)) {
    const s = scoreChapter(text, ch);
    if (s > bestScore) {
      bestScore = s;
      best = ch;
    }
  }
  return bestScore > 0 ? best : null;
}

