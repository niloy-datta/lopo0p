function mergeFactory(baseFactory, extraTemplates) {
  return (seed, q) => {
    const all = [...extraTemplates];
    const baseIdx = (seed + q) % 500;
    try {
      const base = baseFactory(seed, q);
      if (base) return base;
    } catch {
      /* fall through */
    }
    return all[(baseIdx + q) % all.length]();
  };
}

function combineFactories(baseFactory, extraTemplates) {
  return (seed, q) => {
    const pick = (seed + q * 13) % (extraTemplates.length + 30);
    if (pick < extraTemplates.length) return extraTemplates[pick]();
    return baseFactory(seed, q);
  };
}

