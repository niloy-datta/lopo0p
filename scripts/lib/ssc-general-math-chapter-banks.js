const CH12_BASE = require("../data/ssc-general-math-ch12-base-bank.json");

function shuffleWithSeed(arr, seed) {
  const a = [...arr];
  let s = seed;
  for (let i = a.length - 1; i > 0; i--) {
    s = (s * 1103515245 + 12345) & 0x7fffffff;
    const j = s % (i + 1);
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

function makeMcq(text, options, answerIndex, explanation) {
  return { text, options, answerIndex, explanation };
}

function buildCh12ExtendedBank() {
  const bank = [...CH12_BASE];
  const seen = new Set(bank.map((q) => q.text));

  const add = (q) => {
    if (seen.has(q.text)) return;
    seen.add(q.text);
    bank.push(q);
  };

  const subsetTemplates = [
    (n) =>
      makeMcq(
        `{${Array.from({ length: n }, (_, i) => i + 1).join(", ")}} সেটের প্রকৃত উপসেটের সংখ্যা কত?`,
        shuffleWithSeed(
          [String(2 ** n - 1), String(2 ** n), String(n), String(n + 1)],
          n,
        ),
        0,
        `${n}টি পদের প্রকৃত উপসেট = 2^${n} − 1 = ${2 ** n - 1}।`,
      ),
    (n) =>
      makeMcq(
        `n(A) = ${n + 5}, n(B) = ${n + 2}, n(A ∩ B) = ${n} হলে n(A ∪ B) কত?`,
        shuffleWithSeed(
          [
            String(n + 5 + n + 2 - n),
            String(n + 5 + n + 2),
            String(n),
            String(n + 2),
          ],
          n + 3,
        ),
        0,
        `n(A ∪ B) = ${n + 5} + ${n + 2} − ${n} = ${n + 5 + n + 2 - n}।`,
      ),
  ];

  for (let n = 3; n <= 12; n++) {
    for (const fn of subsetTemplates) add(fn(n));
  }

  const unions = [
    ["{1,2}", "{2,3}", "{1,2,3}"],
    ["{2,4}", "{4,6}", "{2,4,6}"],
    ["{1,3,5}", "{3,5,7}", "{1,3,5,7}"],
    ["{a,b}", "{b,c}", "{a,b,c}"],
    ["{2,5}", "{5,8}", "{2,5,8}"],
  ];
  unions.forEach(([a, b, ans], i) => {
    add(
      makeMcq(
        `A = ${a}, B = ${b} হলে A ∪ B কোনটি?`,
        shuffleWithSeed([ans, a, b, "φ"], i + 10),
        0,
        `A ∪ B = ${ans}।`,
      ),
    );
  });

  const builders = [
    ["{x ∈ N : x < 5}", "{1,2,3,4}"],
    ["{x ∈ N : 2 ≤ x ≤ 6}", "{2,3,4,5,6}"],
    ["{x ∈ N : x > 8 এবং x < 12}", "{9,10,11}"],
    ["{x ∈ Z : −1 ≤ x ≤ 1}", "{−1,0,1}"],
    ["{x ∈ N : x একটি জোড় সংখ্যা এবং x < 7}", "{2,4,6}"],
  ];
  builders.forEach(([rule, ans], i) => {
    add(
      makeMcq(
        `${rule} সেটটির তালিকা পদ্ধতিতে প্রকাশ কোনটি?`,
        shuffleWithSeed([ans, "{1,2,3}", "{0,1,2}", "φ"], i + 30),
        0,
        `সেট = ${ans}।`,
      ),
    );
  });

  const equations = [
    ["x² − 4 = 0", "{−2, 2}"],
    ["x² − 5x + 6 = 0", "{2, 3}"],
    ["2x + 3 = 11", "{4}"],
    ["x² = 16", "{−4, 4}"],
    ["3x − 9 = 0", "{3}"],
    ["x² + x − 12 = 0", "{−4, 3}"],
    ["5x = 20", "{4}"],
    ["x² − 9 = 0", "{−3, 3}"],
  ];
  equations.forEach(([eq, ans], i) => {
    add(
      makeMcq(
        `${eq} সমীকরণের সমাধান সেট কোনটি?`,
        shuffleWithSeed([ans, "{0}", "{1}", "φ"], i + 40),
        0,
        `সমাধান সেট = ${ans}।`,
      ),
    );
  });

  const moreEq = [
    ["x + 5 = 12", "{7}"],
    ["x − 3 = 4", "{7}"],
    ["4x = 20", "{5}"],
    ["x/3 = 4", "{12}"],
    ["x² = 49", "{−7, 7}"],
    ["x² − 6x + 9 = 0", "{3}"],
    ["x² + 4x + 4 = 0", "{−2}"],
    ["2x + 1 = 9", "{4}"],
    ["5x − 2 = 18", "{4}"],
    ["x² − x − 20 = 0", "{−4, 5}"],
    ["3x + 6 = 0", "{−2}"],
    ["x² = 0", "{0}"],
    ["x² − 1 = 0", "{−1, 1}"],
    ["x² − 16 = 0", "{−4, 4}"],
    ["6x = 3", "{1/2}"],
    ["x + x = 10", "{5}"],
    ["2(x+1)=8", "{3}"],
    ["x² = 25", "{−5, 5}"],
    ["x² − 2x = 0", "{0, 2}"],
    ["x² + 5x + 6 = 0", "{−2, −3}"],
  ];
  moreEq.forEach(([eq, ans], i) => {
    add(
      makeMcq(
        `${eq} এর সমাধান সেট কোনটি?`,
        shuffleWithSeed([ans, "{0}", "{1}", "φ"], i + 60),
        0,
        `সমাধান সেট = ${ans}।`,
      ),
    );
  });

  const roster = [
    ["{x ∈ N : x ≤ 4}", "{1,2,3,4}"],
    ["{x ∈ N : x > 7 এবং x < 11}", "{8,9,10}"],
    ["{x ∈ N : x জোড় এবং x < 9}", "{2,4,6,8}"],
    ["{x ∈ N : x বেজোড় এবং x ≤ 7}", "{1,3,5,7}"],
    ["{x ∈ Z : 0 ≤ x ≤ 3}", "{0,1,2,3}"],
    ["{x ∈ N : x 5 এর গুণিতক এবং x ≤ 20}", "{5,10,15,20}"],
    ["{x ∈ N : x 4 এর গুণিতক এবং x < 17}", "{4,8,12,16}"],
    ["{x ∈ N : x < 6}", "{1,2,3,4,5}"],
    ["{x ∈ N : 3 ≤ x ≤ 7}", "{3,4,5,6,7}"],
    ["{x ∈ N : x² < 10}", "{1,2,3}"],
  ];
  roster.forEach(([rule, ans], i) => {
    add(
      makeMcq(
        `${rule} সেটের তালিকা রূপ কোনটি?`,
        shuffleWithSeed([ans, "{1,2,3}", "{0,1}", "φ"], i + 80),
        0,
        `সেট = ${ans}।`,
      ),
    );
  });

  const venn = [
    [40, 20, 8, 52],
    [50, 30, 10, 70],
    [60, 25, 15, 70],
    [100, 60, 20, 140],
    [80, 45, 15, 110],
  ];
  venn.forEach(([u, a, ab, union], i) => {
    add(
      makeMcq(
        `n(U)=${u}, n(A)=${a}, n(A∩B)=${ab} হলে n(A∪B)=?`,
        shuffleWithSeed([String(union), String(a + ab), String(u), String(a)], i + 100),
        0,
        `n(A∪B)=${a}+n(B)−${ab}=${union}।`,
      ),
    );
  });

  const diffSets = [
    ["{1,2,3,4}", "{2,4}", "{1,3}"],
    ["{2,3,5,7}", "{3,7}", "{2,5}"],
    ["{a,b,c,d}", "{b,d}", "{a,c}"],
    ["{10,20,30}", "{20}", "{10,30}"],
    ["{1,3,5,7,9}", "{1,3,5}", "{7,9}"],
  ];
  diffSets.forEach(([a, b, ans], i) => {
    add(
      makeMcq(
        `A=${a}, B=${b} হলে A−B কোনটি?`,
        shuffleWithSeed([ans, b, a, "φ"], i + 120),
        0,
        `A−B=${ans}।`,
      ),
    );
  });

  for (let n = 2; n <= 130; n++) {
    const proper = 2 ** n - 1;
    add(
      makeMcq(
        `{${Array.from({ length: Math.min(n, 6) }, (_, i) => i + 1).join(", ")}${n > 6 ? ", ..." : ""}} (${n}টি পদ) সেটের প্রকৃত উপসেট কয়টি?`,
        shuffleWithSeed(
          [String(proper), String(2 ** n), String(n), String(n + 1)],
          n + 200,
        ),
        0,
        `২^${n} − 1 = ${proper}।`,
      ),
    );
  }

  const powerSets = [
    [1, 2],
    [1, 2, 3],
    [2, 3],
  ];
  powerSets.forEach((els, i) => {
    const n = els.length;
    add(
      makeMcq(
        `P({${els.join(", ")}}) এর উপাদান সংখ্যা কত?`,
        shuffleWithSeed([String(2 ** n), String(n), String(2 ** n - 1), String(n + 1)], i + 50),
        0,
        `ক্ষমতা সেটের উপাদান = 2^${n} = ${2 ** n}।`,
      ),
    );
  });

  if (bank.length < 210) {
    throw new Error(`Ch12 bank only ${bank.length} questions, need at least 210`);
  }

  return bank.slice(0, 240);
}

